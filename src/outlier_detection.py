def inspect_dataset_columns(
    df: pd.DataFrame,
    verbose: bool = True,
) -> List[str]:
    """
    Inspects actual columns in Gauri's cleaned dataset and selects appropriate
    numerical features for the Isolation Forest algorithm.

    Excludes identifier, temporal, categorical, and ground-truth metadata columns.

    Parameters:
        df (pd.DataFrame): Input cleaned tourism dataset.
        verbose (bool): If True, prints a formatted summary of inspected columns.

    Returns:
        List[str]: Selected numerical feature names.
    """
    if df.empty:
        raise ValueError("Cannot inspect an empty DataFrame.")

    available_columns = df.columns.tolist()
    numeric_columns = df.select_dtypes(include=[np.number]).columns.tolist()

    # Filter out metadata, ground truth, and date-related numerical columns
    selected_features = [
        col for col in numeric_columns
        if col.strip().lower() not in METADATA_COLUMNS
    ]

    if verbose:
        print("\n" + "=" * 60)
        print(" [Dataset Column Inspection - Melisa's Outlier Module]")
        print("=" * 60)
        print(f"Total Columns Available : {len(available_columns)}")
        print(f"All Columns             : {available_columns}")
        print(f"Numerical Columns Found : {numeric_columns}")
        print(f"Selected Model Features : {selected_features}")
        print("=" * 60 + "\n")

    if not selected_features:
        raise ValueError(
            f"No suitable numerical features found among columns: {available_columns}. "
            "Please ensure Gauri's preprocessed dataset contains numerical tourism metrics."
        )

    return selected_features


def handle_missing_values(
    df: pd.DataFrame,
    feature_cols: List[str],
    impute_strategy: str = "median",
    verbose: bool = True,
) -> pd.DataFrame:
    """
    Inspects and handles missing or non-finite values in the selected feature columns
    prior to passing data to the Isolation Forest algorithm.

    Isolation Forest in scikit-learn requires finite numerical inputs. Missing values
    are imputed per district (or globally) using median values to preserve local baselines.

    Parameters:
        df (pd.DataFrame): Tourism dataframe.
        feature_cols (List[str]): Columns to clean.
        impute_strategy (str): Imputation method ('median', 'mean', or 'zero').
        verbose (bool): Whether to log missing value actions.

    Returns:
        pd.DataFrame: DataFrame with clean, non-null features.
    """
    data = df.copy()
    null_counts = data[feature_cols].isnull().sum()
    total_nulls = null_counts.sum()

    # Replace potential infinite values with NaN for safe imputation
    data[feature_cols] = data[feature_cols].replace([np.inf, -np.inf], np.nan)

    if total_nulls > 0:
        if verbose:
            print(f"[Data Cleaning] Detected {total_nulls} missing values in model features:")
            for col, count in null_counts[null_counts > 0].items():
                print(f"  - {col}: {count} missing")

        for col in feature_cols:
            if data[col].isnull().any():
                if "District" in data.columns:
                    # District-wise median imputation retains district-specific tourist scale
                    data[col] = data.groupby("District")[col].transform(
                        lambda s: s.fillna(s.median() if not s.isnull().all() else 0.0)
                    )
                else:
                    med = data[col].median()
                    data[col] = data[col].fillna(med if not np.isnan(med) else 0.0)
        if verbose:
            print(f"[Data Cleaning] Imputed missing values using {impute_strategy} strategy.")
    else:
        if verbose:
            print("[Data Cleaning] Zero missing values detected in selected feature columns. Dataset clean.")

    return data


class TourismIsolationForest:
    """
    Configurable Isolation Forest wrapper tailored for Kerala Tourism Outlier Detection.

    Concept:
    --------
    Isolation Forest recursively partitions feature space using random thresholds.
    Anomalous observations (e.g., massive festival surges or disaster crashes) have
    few neighbors and are isolated in significantly fewer splits (shorter path lengths)
    than standard seasonal tourist observations.

    Parameters:
        contamination (float or 'auto'): Expected proportion of outliers.
            Defaults to 0.05 (5%). Must be in (0, 0.5] or 'auto'.
        n_estimators (int): Number of isolation trees (default: 150).
        random_state (int): Seed for reproducible random splits.
    """

    def __init__(
        self,
        contamination: Union[float, str] = 0.05,
        n_estimators: int = 150,
        random_state: int = 42,
    ):
        if isinstance(contamination, float):
            if not (0.0 < contamination <= 0.5):
                raise ValueError(
                    f"Contamination must be in range (0.0, 0.5], got: {contamination}. "
                    "Alternatively, use 'auto'."
                )
        elif contamination != "auto":
            raise ValueError(
                f"Contamination must be float in (0.0, 0.5] or 'auto', got: {contamination}"
            )

        self.contamination = contamination
        self.n_estimators = n_estimators
        self.random_state = random_state

        self.model = IsolationForest(
            contamination=self.contamination,
            n_estimators=self.n_estimators,
            random_state=self.random_state,
            n_jobs=-1,
        )
        self.scaler = StandardScaler()
        self.is_fitted = False
        self.feature_names_: List[str] = []

    def fit_predict(
        self,
        df: pd.DataFrame,
        feature_cols: List[str],
    ) -> Tuple[np.ndarray, np.ndarray]:
        """
        Fits the Isolation Forest on scaled numerical features and predicts outliers.

        Parameters:
            df (pd.DataFrame): Data containing feature columns.
            feature_cols (List[str]): Numerical columns to model.

        Returns:
            Tuple[np.ndarray, np.ndarray]:
                - is_outlier: Binary array (1 = outlier, 0 = normal observation).
                - anomaly_score: Continuous anomaly scores (higher = more anomalous).
        """
        self.feature_names_ = feature_cols
        X_raw = df[feature_cols].values

        # Standardize features so features with large scales (e.g., Total_Tourists)
        # do not dominate features with small scales (e.g., Average_Stay_Days)
        X_scaled = self.scaler.fit_transform(X_raw)

        self.model.fit(X_scaled)
        self.is_fitted = True

        # scikit-learn returns -1 for outlier, 1 for inlier
        raw_preds = self.model.predict(X_scaled)

        # Requirement 7: Map to 1 for detected outliers and 0 for normal observations
        is_outlier = np.where(raw_preds == -1, 1, 0)

        # In scikit-learn, score_samples returns opposite of anomaly score
        # (lower values indicate more abnormal). We invert it so higher = more abnormal.
        anomaly_score = -self.model.score_samples(X_scaled)

        return is_outlier, anomaly_score


def detect_outliers_isolation_forest(
    data: Union[str, pd.DataFrame],
    feature_cols: Optional[List[str]] = None,
    contamination: Union[float, str] = 0.05,
    random_state: int = 42,
    output_path: Optional[str] = None,
    verbose: bool = True,
) -> Tuple[pd.DataFrame, TourismIsolationForest]:
    """
    Main reusable interface for detecting outliers in Kerala tourism data.

    Steps:
      1. Loads dataset from path (if str passed) or uses existing DataFrame.
      2. Programmatically inspects columns to select numerical features if not specified.
      3. Handles any missing values via median imputation.
      4. Configures and executes scikit-learn's Isolation Forest.
      5. Adds `is_outlier` (1 = outlier, 0 = normal) and `anomaly_score` columns.
      6. Saves results to `output_path` (default: results/isolation_forest_results.csv) if provided.

    Parameters:
        data (str or pd.DataFrame): Path to `data/processed_tourism.csv` or loaded DataFrame.
        feature_cols (Optional[List[str]]): Specific features to use. If None, auto-detected.
        contamination (float or 'auto'): Expected outlier proportion (default: 0.05).
        random_state (int): Random seed for reproducibility.
        output_path (Optional[str]): Path to export results CSV.
        verbose (bool): Whether to log progress.

    Returns:
        Tuple[pd.DataFrame, TourismIsolationForest]:
            - Enriched DataFrame with `is_outlier` and `anomaly_score`.
            - Trained model wrapper object.
    """
    # Step 1: Ingestion
    if isinstance(data, str):
        if not os.path.exists(data):
            # Graceful fallback check for root vs relative paths
            alt_path = os.path.join(os.getcwd(), data)
            if not os.path.exists(alt_path):
                raise FileNotFoundError(
                    f"Processed tourism dataset not found at '{data}'. "
                    "Ensure Gauri's preprocessing pipeline has generated 'data/processed_tourism.csv'."
                )
            data = alt_path
        df = pd.read_csv(data)
        if verbose:
            print(f"[Data Ingestion] Successfully loaded {len(df):,} records from: {data}")
    elif isinstance(data, pd.DataFrame):
        df = data.copy()
        if verbose:
            print(f"[Data Ingestion] Processing input DataFrame with {len(df):,} records.")
    else:
        raise TypeError("Input 'data' must be a filepath string or a pandas DataFrame.")

    # Step 2: Column Inspection & Feature Selection
    if feature_cols is None:
        feature_cols = inspect_dataset_columns(df, verbose=verbose)
    else:
        missing_requested = [c for c in feature_cols if c not in df.columns]
        if missing_requested:
            raise KeyError(f"Requested features not found in dataset: {missing_requested}")

    # Step 3: Handle Missing Values
    cleaned_df = handle_missing_values(df, feature_cols, verbose=verbose)

    # Step 4: Run Configurable Isolation Forest
    if verbose:
        print(f"[Model Execution] Initializing Isolation Forest (contamination={contamination})...")

    detector = TourismIsolationForest(
        contamination=contamination,
        random_state=random_state,
    )
    is_outlier, anomaly_scores = detector.fit_predict(cleaned_df, feature_cols)

    # Step 5: Append Outlier Results
    result_df = cleaned_df.copy()
    result_df["is_outlier"] = is_outlier
    result_df["anomaly_score"] = np.round(anomaly_scores, 4)

    # Contextual Explanation (Requirement 9)
    n_outliers = int(is_outlier.sum())
    outlier_pct = (n_outliers / len(result_df)) * 100

    if verbose:
        print("\n" + "-" * 60)
        print(" [Isolation Forest Outlier Detection Summary]")
        print("-" * 60)
        print(f"Total Observations Screened : {len(result_df):,}")
        print(f"Detected Outliers (is_outlier=1): {n_outliers:,} ({outlier_pct:.2f}%)")
        print(f"Normal Observations (is_outlier=0): {len(result_df) - n_outliers:,} ({100 - outlier_pct:.2f}%)")
        print("=" * 60)
        print(" NOTE ON OUTLIER INTERPRETATION:")
        print(" Detected outliers in Kerala tourism data represent statistically")
        print(" UNUSUAL OBSERVATIONS (e.g. 2018 flood crises, COVID drops, or")
        print(" festive Onam/Pooram surges), NOT necessarily errors or bad data.")
        print("=" * 60 + "\n")

    # Step 6: Export results
    if output_path:
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        result_df.to_csv(output_path, index=False)
        if verbose:
            print(f"[Results Export] Output saved to: {output_path}")

    return result_df, detector


def plot_isolation_forest_visualizations(
    df: pd.DataFrame,
    save_path: Optional[str] = DEFAULT_FIGURE_PATH,
    show: bool = False,
):
    """
    Requirement 10: Creates rich visualizations clearly distinguishing detected
    outliers from normal observations using Matplotlib.

    Generates a 3-panel figure:
      1. Bivariate Scatter Plot: Domestic vs. Foreign Tourists with distinct colors/markers.
      2. Time Series Trajectory: Monthly arrivals over time highlighting crisis drops & festival spikes.
      3. Anomaly Score Distribution: Histogram distinguishing normal points from outliers.

    Parameters:
        df (pd.DataFrame): DataFrame containing `is_outlier`, `anomaly_score`, and features.
        save_path (Optional[str]): File path to save the generated figure.
        show (bool): Whether to display the plot interactively.
    """
    if "is_outlier" not in df.columns:
        raise KeyError("DataFrame must contain 'is_outlier' column to plot.")

    normal = df[df["is_outlier"] == 0]
    outliers = df[df["is_outlier"] == 1]

    fig, axes = plt.subplots(2, 2, figsize=(15, 11), dpi=200)

    # -------------------------------------------------------------
    # Plot 1: Bivariate Scatter (Domestic vs. Foreign Tourists)
    # -------------------------------------------------------------
    ax1 = axes[0, 0]
    ax1.scatter(
        normal["Domestic_Tourists"] if "Domestic_Tourists" in normal.columns else normal["Total_Tourists"],
        normal["Foreign_Tourists"] if "Foreign_Tourists" in normal.columns else normal.iloc[:, 0],
        color="#2b7bba",
        alpha=0.6,
        s=35,
        label=f"Normal Observations (N={len(normal)})",
    )
    ax1.scatter(
        outliers["Domestic_Tourists"] if "Domestic_Tourists" in outliers.columns else outliers["Total_Tourists"],
        outliers["Foreign_Tourists"] if "Foreign_Tourists" in outliers.columns else outliers.iloc[:, 0],
        color="#d9381e",
        alpha=0.9,
        s=70,
        marker="X",
        edgecolor="black",
        linewidth=0.8,
        label=f"Detected Outliers (N={len(outliers)})",
        zorder=5,
    )
    ax1.set_title("Domestic vs. Foreign Arrivals (Outliers Highlighted)", fontweight="bold")
    ax1.set_xlabel("Domestic Tourists")
    ax1.set_ylabel("Foreign Tourists")
    ax1.legend(loc="upper right", frameon=True)
    ax1.grid(True, linestyle="--", alpha=0.5)

    # -------------------------------------------------------------
    # Plot 2: Hotel Occupancy vs Tourism Revenue
    # -------------------------------------------------------------
    ax2 = axes[0, 1]
    if "Hotel_Occupancy_Rate" in df.columns and "Tourism_Revenue_Cr" in df.columns:
        ax2.scatter(
            normal["Hotel_Occupancy_Rate"],
            normal["Tourism_Revenue_Cr"],
            color="#2a9d8f",
            alpha=0.6,
            s=35,
            label="Normal",
        )
        ax2.scatter(
            outliers["Hotel_Occupancy_Rate"],
            outliers["Tourism_Revenue_Cr"],
            color="#e76f51",
            alpha=0.9,
            s=70,
            marker="s",
            edgecolor="black",
            linewidth=0.8,
            label="Outlier",
            zorder=5,
        )
        ax2.set_title("Hotel Occupancy (%) vs. Revenue (₹ Cr)", fontweight="bold")
        ax2.set_xlabel("Hotel Occupancy Rate (%)")
        ax2.set_ylabel("Tourism Revenue (₹ Crores)")
        ax2.legend(loc="upper left", frameon=True)
        ax2.grid(True, linestyle="--", alpha=0.5)
    else:
        # Fallback feature scatter
        ax2.text(0.5, 0.5, "Revenue/Occupancy not in dataset", ha="center", va="center")

    # -------------------------------------------------------------
    # Plot 3: Time Series Trajectory with Outlier Markers
    # -------------------------------------------------------------
    ax3 = axes[1, 0]
    if "Date" in df.columns:
        df_sorted = df.copy()
        df_sorted["Date"] = pd.to_datetime(df_sorted["Date"])
        df_sorted = df_sorted.sort_values(by="Date")

        # Plot total state arrivals by month
        monthly_total = df_sorted.groupby("Date")["Total_Tourists"].sum().reset_index()
        monthly_outlier = df_sorted[df_sorted["is_outlier"] == 1].groupby("Date")["Total_Tourists"].sum().reset_index()

        ax3.plot(
            monthly_total["Date"],
            monthly_total["Total_Tourists"],
            color="#1d3557",
            linewidth=1.8,
            label="Total State Arrivals",
        )
        ax3.scatter(
            monthly_outlier["Date"],
            monthly_outlier["Total_Tourists"],
            color="#e63946",
            s=65,
            marker="o",
            edgecolor="black",
            zorder=5,
            label="Anomalous Months (Outliers)",
        )
        ax3.set_title("Timeline: Monthly Tourist Arrivals & Outlier Markers", fontweight="bold")
        ax3.set_xlabel("Timeline")
        ax3.set_ylabel("Monthly Total Tourists")
        ax3.legend(loc="upper right", frameon=True)
        ax3.grid(True, linestyle="--", alpha=0.5)
    else:
        ax3.text(0.5, 0.5, "Date column not available", ha="center", va="center")

    # -------------------------------------------------------------
    # Plot 4: Anomaly Score Distribution
    # -------------------------------------------------------------
    ax4 = axes[1, 1]
    if "anomaly_score" in df.columns:
        ax4.hist(
            normal["anomaly_score"],
            bins=30,
            color="#457b9d",
            alpha=0.7,
            label="Normal Score Distribution",
            density=True,
        )
        ax4.hist(
            outliers["anomaly_score"],
            bins=20,
            color="#e63946",
            alpha=0.7,
            label="Outlier Score Distribution",
            density=True,
        )
        threshold_approx = outliers["anomaly_score"].min()
        ax4.axvline(
            threshold_approx,
            color="black",
            linestyle="--",
            linewidth=1.5,
            label=f"Decision Boundary (~{threshold_approx:.3f})",
        )
        ax4.set_title("Isolation Forest Anomaly Score Distribution", fontweight="bold")
        ax4.set_xlabel("Anomaly Score (Higher = More Unusual)")
        ax4.set_ylabel("Density")
        ax4.legend(loc="upper right", frameon=True)
        ax4.grid(True, linestyle="--", alpha=0.5)

    plt.tight_layout()

    if save_path:
        os.makedirs(os.path.dirname(save_path), exist_ok=True)
        plt.savefig(save_path, bbox_inches="tight")
        plt.close()
        print(f"[Visualizations] Saved outlier diagnostic charts to: {save_path}")
    elif show:
        plt.show()


