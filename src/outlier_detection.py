class StatisticalOutlierDetector:
    """Statistical outlier baseline detector."""
    @staticmethod
    def detect_zscore(series: pd.Series, threshold: float = 3.0) -> pd.Series:
        mean, std = series.mean(), series.std()
        return ((series - mean).abs() / (std if std != 0 else 1.0) > threshold).astype(int)

    @staticmethod
    def detect_modified_zscore(series: pd.Series, threshold: float = 3.5) -> pd.Series:
        med = series.median()
        mad = np.median(np.abs(series - med))
        return (0.6745 * (series - med).abs() / (mad if mad != 0 else 1.0) > threshold).astype(int)

    @staticmethod
    def detect_iqr(series: pd.Series, multiplier: float = 1.5) -> pd.Series:
        q25, q75 = series.quantile(0.25), series.quantile(0.75)
        iqr = q75 - q25
        return ((series < (q25 - multiplier * iqr)) | (series > (q75 + multiplier * iqr))).astype(int)

    @classmethod
    def apply_district_group_iqr(cls, df: pd.DataFrame, target_col="Total_Tourists", group_col="District", multiplier=1.5):
        return df.groupby(group_col)[target_col].transform(lambda s: cls.detect_iqr(s, multiplier=multiplier)).astype(int)


class MLOutlierDetector:
    """Multi-model ML wrapper supporting group integration."""
    def __init__(self, contamination=0.05, random_state=42):
        self.contamination = contamination
        self.random_state = random_state
        self.models = {}

    def fit_isolation_forest(self, X):
        model = IsolationForest(contamination=self.contamination, random_state=self.random_state, n_jobs=-1)
        preds = model.fit_predict(X)
        self.models["Isolation_Forest"] = model
        return (preds == -1).astype(int), -model.score_samples(X)

    def fit_lof(self, X, n_neighbors=20):
        from sklearn.neighbors import LocalOutlierFactor
        model = LocalOutlierFactor(n_neighbors=n_neighbors, contamination=self.contamination, n_jobs=-1)
        preds = model.fit_predict(X)
        self.models["LOF"] = model
        return (preds == -1).astype(int), -model.negative_outlier_factor_

    def fit_one_class_svm(self, X):
        from sklearn.svm import OneClassSVM
        model = OneClassSVM(nu=self.contamination, kernel="rbf", gamma="scale")
        preds = model.fit_predict(X)
        self.models["OneClass_SVM"] = model
        return (preds == -1).astype(int), -model.score_samples(X)

    def fit_elliptic_envelope(self, X):
        from sklearn.covariance import EllipticEnvelope
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", category=RuntimeWarning)
                model = EllipticEnvelope(contamination=self.contamination, random_state=self.random_state, support_fraction=None)
                preds = model.fit_predict(X)
                self.models["Elliptic_Envelope"] = model
                return (preds == -1).astype(int), model.mahalanobis(X)
        except Exception:
            return np.zeros(len(X), dtype=int), np.zeros(len(X))

    def fit_dbscan(self, X, eps=1.8, min_samples=5):
        from sklearn.cluster import DBSCAN
        model = DBSCAN(eps=eps, min_samples=min_samples, n_jobs=-1)
        preds = model.fit_predict(X)
        self.models["DBSCAN"] = model
        return (preds == -1).astype(int)


class EnsembleOutlierDetector:
    """Ensemble consensus aggregator."""
    def __init__(self, min_consensus_votes: int = 2):
        self.min_consensus_votes = min_consensus_votes

    def vote(self, pred_dict: Dict[str, np.ndarray]):
        vote_matrix = np.column_stack(list(pred_dict.values()))
        total_votes = np.sum(vote_matrix, axis=1)
        anomaly_score = total_votes / max(1, vote_matrix.shape[1])
        consensus_outliers = (total_votes >= self.min_consensus_votes).astype(int)
        return consensus_outliers, anomaly_score


def run_all_detectors(
    df: pd.DataFrame,
    scaled_features: pd.DataFrame,
    contamination: float = 0.05,
    min_consensus: int = 2,
) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """Enables seamless compatibility with existing main.py pipeline."""
    results_df = df.copy()
    stat = StatisticalOutlierDetector()
    results_df["Outlier_ZScore"] = stat.detect_zscore(results_df["Total_Tourists"])
    results_df["Outlier_ModZScore"] = stat.detect_modified_zscore(results_df["Total_Tourists"])
    results_df["Outlier_IQR_Global"] = stat.detect_iqr(results_df["Total_Tourists"])
    results_df["Outlier_IQR_District"] = stat.apply_district_group_iqr(results_df)

    ml = MLOutlierDetector(contamination=contamination)
    iso_pred, iso_scores = ml.fit_isolation_forest(scaled_features)
    lof_pred, lof_scores = ml.fit_lof(scaled_features)
    ocsvm_pred, ocsvm_scores = ml.fit_one_class_svm(scaled_features)
    ee_pred, ee_scores = ml.fit_elliptic_envelope(scaled_features)
    dbscan_pred = ml.fit_dbscan(scaled_features)

    results_df["Outlier_IsolationForest"] = iso_pred
    results_df["Score_IsolationForest"] = iso_scores
    results_df["Outlier_LOF"] = lof_pred
    results_df["Score_LOF"] = lof_scores
    results_df["Outlier_OneClassSVM"] = ocsvm_pred
    results_df["Score_OneClassSVM"] = ocsvm_scores
    results_df["Outlier_EllipticEnvelope"] = ee_pred
    results_df["Score_EllipticEnvelope"] = ee_scores
    results_df["Outlier_DBSCAN"] = dbscan_pred

    # Melisa's standard is_outlier flag mapped to Isolation Forest
    results_df["is_outlier"] = iso_pred
    results_df["anomaly_score"] = iso_scores

    ensemble = EnsembleOutlierDetector(min_consensus_votes=min_consensus)
    candidate_models = {
        "IsolationForest": iso_pred,
        "LOF": lof_pred,
        "OneClassSVM": ocsvm_pred,
        "IQR_District": results_df["Outlier_IQR_District"].values,
        "ModZScore": results_df["Outlier_ModZScore"].values,
    }
    consensus_flags, ensemble_scores = ensemble.vote(candidate_models)
    results_df["Ensemble_Outlier"] = consensus_flags
    results_df["Ensemble_Anomaly_Score"] = np.round(ensemble_scores, 3)

    return results_df, ml.models


